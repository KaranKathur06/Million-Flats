DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'ModerationEntityType') THEN
    CREATE TYPE "ModerationEntityType" AS ENUM (
      'MANUAL_PROPERTY',
      'AGENT',
      'USER',
      'ECOSYSTEM_PARTNER',
      'ECOSYSTEM_PARTNER_APPLICATION',
      'ECOSYSTEM_PARTNER_MEMBERSHIP',
      'ECOSYSTEM_PARTNER_CHANGE_REQUEST',
      'ECOSYSTEM_CATEGORY'
    );
  ELSE
    ALTER TYPE "ModerationEntityType" ADD VALUE IF NOT EXISTS 'MANUAL_PROPERTY';
    ALTER TYPE "ModerationEntityType" ADD VALUE IF NOT EXISTS 'AGENT';
    ALTER TYPE "ModerationEntityType" ADD VALUE IF NOT EXISTS 'USER';
    ALTER TYPE "ModerationEntityType" ADD VALUE IF NOT EXISTS 'ECOSYSTEM_PARTNER';
    ALTER TYPE "ModerationEntityType" ADD VALUE IF NOT EXISTS 'ECOSYSTEM_PARTNER_APPLICATION';
    ALTER TYPE "ModerationEntityType" ADD VALUE IF NOT EXISTS 'ECOSYSTEM_PARTNER_MEMBERSHIP';
    ALTER TYPE "ModerationEntityType" ADD VALUE IF NOT EXISTS 'ECOSYSTEM_PARTNER_CHANGE_REQUEST';
    ALTER TYPE "ModerationEntityType" ADD VALUE IF NOT EXISTS 'ECOSYSTEM_CATEGORY';
  END IF;
END $$;
